// /llms.txt — AI（ChatGPT・Claude・Perplexity等）向けの店舗要約。
// 「新居浜で31人の宴会ができる店は？」とAIに聞いて当店の予約が入った
// （2026-10-08・団体予約）。AIが店の事実を正確に拾えるよう、人数・個室・
// 貸切・予算・予約方法を1枚のテキストにまとめて置く。中身は site.json から
// ビルド時に組み立てるので、数字を直すとここも自動で揃う。
import type { APIRoute } from 'astro';
import site from '../../data/site.json';

export const GET: APIRoute = ({ site: base }) => {
  const s = site.店舗情報;
  const b = site.宴会コース;
  const a = site.アクセス;
  const r = site.予約問い合わせ;
  const h = site.営業時間;
  const j = site.求人;
  const url = (path: string) => new URL(path, base).href;
  const hours = [...h.表示.map((x) => `${x.曜日} ${x.時間}`), `定休日 ${h.定休日}`];

  const lines = [
    `# ${s.店名}（${s.店名ローマ字}）`,
    '',
    `> 愛媛県新居浜市のおばんざい居酒屋。おひとり様のカウンター飲みから、${b.宴会最大人数.replace(/（.*）/, '')}の団体宴会・貸切まで対応。`,
    '',
    '## 基本情報',
    `- 店名: ${s.店名}`,
    `- 住所: 〒${s.郵便番号} ${s.住所}`,
    `- 電話: ${s.電話番号}`,
    ...hours.map((x) => `- 営業時間: ${x}`),
    `- アクセス: ${a.最寄り}／${a.バス}`,
    `- 駐車場: ${a.駐車場}`,
    `- 喫煙: ${s.喫煙}`,
    `- 公式サイト: ${url('/')}`,
    '',
    '## 宴会・団体利用',
    `- 団体の最大人数: ${b.宴会最大人数}`,
    `- 総席数: ${b.最大収容人数}`,
    `- お席: ${b.個室}`,
    `- 貸切: ${b.貸切}`,
    `- 予算の目安: ${b.予算目安}`,
    ...b.コース一覧.map((c: any) => `- ${c.名称}: ${c.価格}（${c.飲み放題}・${c.品数}）${c.内容}`),
    `- 領収書: ${b.領収書対応}`,
    `- 請求書: ${b.請求書対応}`,
    `- 詳細: ${url('/enkai')}`,
    '',
    '## 予約方法',
    `- ネット予約（24時間・空席がその場で分かる・8名様まで）: ${r.ネット予約URL}`,
    `- 9名様以上・宴会・当日のご予約: 電話 ${s.電話番号}`,
    `- 公式LINE: ${r.lineURL}`,
    `- Instagram: ${site.instagram.プロフィールURL}`,
    '',
    '## よくある質問',
    `- 30名以上の宴会はできますか？ → はい。${b.宴会最大人数}。25名様以上は貸切も可能です。`,
    `- 個室はありますか？ → 掘りごたつの個室（8名様）があります。`,
    `- 会社の経費用の領収書・請求書は出ますか？ → はい。インボイス対応で、宛名・但し書きも対応します。`,
    ...(j?.公開 ? ['', '## スタッフ募集', `- ${j.職種}（${j.雇用形態}）時給${j.時給.toLocaleString('ja-JP')}円〜（22時以降${j.深夜時給.toLocaleString('ja-JP')}円〜）: ${url('/recruit')}`] : []),
    '',
  ];
  return new Response(lines.join('\n'), { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
};
